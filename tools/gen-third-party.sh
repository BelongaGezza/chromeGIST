#!/usr/bin/env bash
# Regenerates chromeGIST's third-party licence disclosure from Cargo.lock:
#
#   docs/THIRD-PARTY.md                        — human-readable table
#   apps/chrome/THIRD_PARTY_NOTICES.txt        — plain-text copy shipped in
#                                                the extension package
#
# Covers every external crate reachable from chromegist-wasm via normal
# (non-dev, non-build) dependency edges *for the wasm32 target* — `cargo tree
# -p chromegist-wasm -e normal --target wasm32-unknown-unknown` — which is
# everything compiled into the .wasm and its JS glue. Workspace crates
# (chromegist-wasm itself) and GIST's gist-* crates (git dependencies on
# github.com/BelongaGezza/gist) are excluded as first-party. Mirrors GIST's docs/THIRD-PARTY.md methodology (reader commit
# 401a972).
#
# Re-run after any Cargo.lock change, including a GIST pin bump
# (tools/upstream-review.sh --record) that alters gist-model/gist-parse-txt/
# gist-rsvp's dependencies.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/contextgist-third-party.XXXXXX")"
trap 'rm -rf "$TMP_DIR"' EXIT

cargo tree -p chromegist-wasm -e normal --target wasm32-unknown-unknown --prefix none --format '{p}' \
    | sed 's/ (.*)//' | sort -u > "$TMP_DIR/tree.txt"
cargo metadata --format-version 1 > "$TMP_DIR/meta.json"

python3 - "$TMP_DIR" "$REPO_ROOT" <<'PY'
import datetime, json, sys

tmp, root = sys.argv[1], sys.argv[2]
meta = json.load(open(f"{tmp}/meta.json"))
packages = {(p["name"], p["version"]): p for p in meta["packages"]}

rows = []
for line in open(f"{tmp}/tree.txt"):
    name, ver = line.split()[:2]
    p = packages[(name, ver.lstrip("v"))]
    # workspace crate or GIST's own (same author): first-party
    if p["source"] is None or p["source"].startswith("git+https://github.com/BelongaGezza/gist"):
        continue
    rows.append((p["name"], p["version"], p.get("license") or "UNKNOWN",
                 p.get("repository") or ""))
rows.sort()
unknown = [r for r in rows if r[2] == "UNKNOWN"]
if unknown:
    sys.exit(f"error: no declared licence for {unknown}; resolve manually")

today = datetime.date.today().isoformat()
n = len(rows)

mpl = [a for a, b, c, d in rows if "MPL" in c]
md = [
    "# Third-party dependencies",
    "",
    "chromeGIST itself is MIT-licensed (see `LICENSE`). Its Rust core",
    "(`crates/chromegist-wasm`, compiled to the extension's WebAssembly) reuses",
    "GIST's `gist-model`/`gist-parse-txt`/`gist-rsvp` crates (MIT, same author,",
    "via a git dependency pinned to a commit) and depends on the external crates below. The",
    "extension's own JavaScript has no third-party dependencies (no npm",
    "packages, no bundled libraries).",
    "",
    "**Generated by `tools/gen-third-party.sh`. Do not edit by hand.** The same",
    "list ships in the extension as `THIRD_PARTY_NOTICES.txt`.",
    "",
    "**Methodology:**",
    f"- Regenerated {today} from `Cargo.lock`: every crate reachable from",
    "  `chromegist-wasm` via `cargo tree -e normal` for wasm32, deduplicated, with each",
    "  crate's declared licence from `cargo metadata`. "
    f"{n} external crates.",
    "- Proc-macro crates (e.g. `wasm-bindgen-macro`) only run at compile time",
    "  and aren't part of the shipped code; they're listed anyway for completeness.",
    "- Checked against this repo's `deny.toml` (adapted from GIST's):",
    "  `cargo deny --exclude-dev check` → `advisories ok, bans ok, licenses",
    "  ok, sources ok`.",
]
if mpl:
    md += [
        f"- **MPL-2.0 ({', '.join(mpl)}):** file-level copyleft. Used unmodified,",
        "  so the obligation is to tell recipients where the source is (the",
        "  repository links below). Modifying those crates' own files would",
        "  require publishing the modified files under MPL-2.0.",
    ]
md += [
    "",
    "| Crate | Version | Licence | Repository |",
    "|---|---|---|---|",
]
md += [f"| {a} | {b} | {c} | <{d}> |" if d else f"| {a} | {b} | {c} | |"
       for a, b, c, d in rows]
open(f"{root}/docs/THIRD-PARTY.md", "w").write("\n".join(md) + "\n")

txt = [
    "chromeGIST — Third-Party Notices",
    "=================================",
    "",
    "chromeGIST is licensed under the MIT License.",
    "",
    "Its Rust core (statically linked into this app; there are no other",
    "third-party dependencies) depends on the following third-party Rust",
    "crates. The source code of each is available at the repository listed.",
    "",
    f"Rust dependencies ({n} crates)",
    "-" * len(f"Rust dependencies ({n} crates)"),
    "",
]
for a, b, c, d in rows:
    txt.append(f"{a} {b} -- {c}")
    if d:
        txt.append(f"  {d}")
    txt.append("")
open(f"{root}/apps/chrome/THIRD_PARTY_NOTICES.txt", "w").write("\n".join(txt))
print(f"✓ {n} crates written to docs/THIRD-PARTY.md and "
      "apps/chrome/THIRD_PARTY_NOTICES.txt")
PY
